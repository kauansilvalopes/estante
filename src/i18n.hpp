inline void (*on_miss)(const char *) = nullptr; // host preview only: report untranslated text
inline const char *tr(const char *pt)
{
    if (language == 0 || !pt)
        return pt;
    for (const auto &e : table)
        if (!std::strcmp(e.pt, pt))
            return e.en;
    if (on_miss)
        on_miss(pt);
    return pt;
}
